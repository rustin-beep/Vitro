// gen_course —— 课程叙述层生成器（#120 课程内容管线，2026-10-15）。
//
// **【2026-10-15 退役标注】lessons.ts 渲染角色退役（#125 批 A 形态修正）**：
// 「资产链自举」判据（下游不装额外工具链能否再生资产）驳回 Go 进资产链
// ——本生成器为 Go、且 HTML 预渲染进资产，两者均被判据排除。保留本体
// 作为**失败回退预案**（content.json 静态发射形态，宿主运行时方案
// （parser.c + demo 运行时喂引擎解析）失败时可用）；CI/pages 接线已摘。
// course_catalog（防线）不受影响继续在役。
//
// 真源 = course/<chap>/<id>/lesson.md（frontmatter + 正文，教师手写面）；
// 产物 = demo/src/data/lessons.ts（类型化 ESM，demo 侧按 id 与 cases.js /
// algorithms.js 课目集 join——本生成器不消费代码链，代码真源仍为
// cases.js 与 templates/*/source.c，「代码两份」病结构性排除）。
//
// 正由 vitrb course_catalog 闸兜底：digest 同步 + id 值域对账 + J9 证红。
//
// 用法：
//
//	go run ./gen_course            // 再生 demo/src/data/lessons.ts
//	go run ./gen_course -check     // 只比对不落盘（CI 闸；不一致 exit 1）
//
// 契约（照 gen_diag 形态）：输出文件 @generated 首行；幂等（遍历字典序 +
// 确定性序列化，双次运行字节一致）；-check 不留副作用。
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"vitro/scripts/internal/mdrender"
)

const (
	courseDir  = "course"
	headerNote = `// @generated by scripts/gen_course — 勿手改；真源 course/**/*.md，再生 go run ./scripts/gen_course
// 教学叙述层（#120 课程内容管线）：id = 课目键（cases 用例 id / 族 id / variant 模板名 / xlab id），
// demo 侧按 (kind,id) 与 cases.js + algorithms.js join；html = lesson.md 正文的构建期预渲染片段。
export interface LessonNote {
  id: string;
  kind: "case" | "algo" | "variant" | "xlab";
  chap: string;
  order: number;
  famId?: string;
  stdin?: string;
  html: string;
}
export const LESSON_NOTES: LessonNote[] = [
`
	footerNote = "];\n"
)

// outPath 产物落点（demo/src/data/lessons.ts——Svelte 侧 import 的唯一面）。
var outPath = filepath.Join("demo", "src", "data", "lessons.ts")

type lesson struct {
	ID    string
	Kind  string
	Chap  string
	Order int
	FamID string
	Stdin string
	HTML  string
	Dir   string
}

func die(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "[gen_course] "+format+"\n", args...)
	os.Exit(1)
}

// parseFrontmatter 解析 --- 围栏内的 key: value 行（轻量形态，不支持嵌套结构）。
func parseFrontmatter(src string) (map[string]string, string, error) {
	fm := map[string]string{}
	s := strings.ReplaceAll(src, "\r\n", "\n")
	if !strings.HasPrefix(s, "---\n") {
		return nil, s, fmt.Errorf("缺 frontmatter 开栏（文件须以 --- 行开始）")
	}
	body := strings.TrimPrefix(s, "---\n")
	end := strings.Index(body, "\n---")
	if end < 0 {
		return nil, s, fmt.Errorf("缺 frontmatter 收栏 ---")
	}
	for i, line := range strings.Split(body[:end], "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		k, v, ok := strings.Cut(line, ":")
		if !ok {
			return nil, s, fmt.Errorf("frontmatter 第 %d 行非 key: value 形态: %q", i+1, line)
		}
		fm[strings.TrimSpace(k)] = strings.Trim(strings.TrimSpace(v), `"'`)
	}
	return fm, body[end+4:], nil
}

func collect() ([]*lesson, error) {
	var out []*lesson
	entries, err := os.ReadDir(courseDir)
	if err != nil {
		return nil, fmt.Errorf("读 %s: %w", courseDir, err)
	}
	for _, chap := range entries {
		if !chap.IsDir() || strings.HasPrefix(chap.Name(), ".") {
			continue
		}
		lessons, err := os.ReadDir(filepath.Join(courseDir, chap.Name()))
		if err != nil {
			return nil, err
		}
		for _, l := range lessons {
			if !l.IsDir() {
				continue
			}
			dir := filepath.Join(courseDir, chap.Name(), l.Name())
			mdPath := filepath.Join(dir, "lesson.md")
			src, err := os.ReadFile(mdPath)
			if err != nil {
				continue // 目录无 lesson.md 非错误（允许草稿目录）
			}
			fm, body, err := parseFrontmatter(string(src))
			if err != nil {
				return nil, fmt.Errorf("%s: %w", mdPath, err)
			}
			les := &lesson{Dir: dir, Chap: chap.Name(), HTML: mdrender.Fragment(body)}
			for k, v := range fm {
				switch k {
				case "id":
					les.ID = v
				case "kind":
					les.Kind = v
				case "order":
					fmt.Sscanf(v, "%d", &les.Order)
				case "famId":
					les.FamID = v
				case "stdin":
					les.Stdin = v
				case "title":
					// 标题进叙述正文由 <h?> 承载；frontmatter title 仅作文档习惯保留
				default:
					return nil, fmt.Errorf("%s: 未知 frontmatter 字段 %q（schema 见 gen_course 头注）", mdPath, k)
				}
			}
			if les.ID == "" || les.Kind == "" {
				return nil, fmt.Errorf("%s: id/kind 必填", mdPath)
			}
			switch les.Kind {
			case "case", "algo", "variant", "xlab":
			default:
				return nil, fmt.Errorf("%s: kind %q 不在 case|algo|variant|xlab", mdPath, les.Kind)
			}
			if les.Kind == "variant" && les.FamID == "" {
				return nil, fmt.Errorf("%s: kind=variant 须带 famId", mdPath)
			}
			if les.Order == 0 {
				les.Order = 999 // 缺省排章尾
			}
			out = append(out, les)
		}
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Chap != out[j].Chap {
			return out[i].Chap < out[j].Chap
		}
		if out[i].Order != out[j].Order {
			return out[i].Order < out[j].Order
		}
		return out[i].ID < out[j].ID
	})
	return out, nil
}

func emit(lessons []*lesson) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(headerNote)
	for i, l := range lessons {
		idJSON, _ := json.Marshal(l.ID)
		kindJSON, _ := json.Marshal(l.Kind)
		chapJSON, _ := json.Marshal(l.Chap)
		htmlJSON, _ := json.Marshal(l.HTML)
		b.WriteString("  {\n")
		fmt.Fprintf(&b, "    id: %s,\n", idJSON)
		fmt.Fprintf(&b, "    kind: %s,\n", kindJSON)
		fmt.Fprintf(&b, "    chap: %s,\n", chapJSON)
		fmt.Fprintf(&b, "    order: %d,\n", l.Order)
		if l.FamID != "" {
			f, _ := json.Marshal(l.FamID)
			fmt.Fprintf(&b, "    famId: %s,\n", f)
		}
		if l.Stdin != "" {
			s, _ := json.Marshal(l.Stdin)
			fmt.Fprintf(&b, "    stdin: %s,\n", s)
		}
		fmt.Fprintf(&b, "    html: %s,\n", htmlJSON)
		b.WriteString("  }")
		if i < len(lessons)-1 {
			b.WriteString(",")
		}
		b.WriteString("\n")
	}
	b.WriteString(footerNote)
	return b.Bytes(), nil
}

func main() {
	check := flag.Bool("check", false, "只比对生成物不落盘（CI 闸）：不一致 exit 1")
	flag.Parse()

	lessons, err := collect()
	if err != nil {
		die("%v", err)
	}
	out, err := emit(lessons)
	if err != nil {
		die("序列化: %v", err)
	}

	existing, readErr := os.ReadFile(outPath)
	if *check {
		if readErr != nil {
			die("-check: 生成物不可读（先跑一次再生）: %v", readErr)
		}
		if !bytes.Equal(existing, out) {
			die("-check: demo/src/data/lessons.ts 与现算不一致（真源已改未再生）——跑 go run ./scripts/gen_course 再生后提交")
		}
		fmt.Printf("[gen_course] -check OK：%d 课叙述与生成物一致\n", len(lessons))
		return
	}
	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		die("建目录: %v", err)
	}
	if err := os.WriteFile(outPath, out, 0o644); err != nil {
		die("写产物: %v", err)
	}
	fmt.Printf("[gen_course] 生成 %s（%d 课叙述）\n", outPath, len(lessons))
}
